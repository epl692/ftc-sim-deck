# One-time setup for Windows 10/11 (WSL2 + WSLg). Run in PowerShell:
#   irm https://raw.githubusercontent.com/epl692/ftc-sim-deck/main/install.ps1 | iex
# Installs a dedicated Ubuntu WSL distro, podman + git inside it, runs the normal Linux install.sh,
# and adds an "FTC Simulator" shortcut to the Desktop and Start menu. Safe to re-run.
$ErrorActionPreference = 'Stop'

$Distro   = 'Ubuntu-24.04'
$User     = 'ftc'
$Repo     = if ($env:FTC_TOOLS_REPO) { $env:FTC_TOOLS_REPO } else { 'https://github.com/epl692/ftc-sim-deck.git' }
$RawBase  = 'https://raw.githubusercontent.com/epl692/ftc-sim-deck/main'
$AppDir   = Join-Path $env:LOCALAPPDATA 'ftc-sim'

function Test-Distro { (wsl.exe --list --quiet 2>$null | ForEach-Object { ($_ -replace "`0", '').Trim() }) -contains $Distro }

# --- 1. WSL + distro ---------------------------------------------------------------------------
if (-not (Get-Command wsl.exe -ErrorAction SilentlyContinue)) {
    throw 'wsl.exe not found. This needs Windows 10 (2004+) or Windows 11.'
}
if (-not (Test-Distro)) {
    Write-Host "==> Installing WSL and $Distro (needs admin; may require a reboot)"
    wsl.exe --install -d $Distro --no-launch
    if ($LASTEXITCODE -ne 0) { throw 'WSL install failed. Run PowerShell as Administrator and try again.' }
    # Register the distro non-interactively (as root; we create our own user below).
    $launcher = 'ubuntu2404.exe'
    if (Get-Command $launcher -ErrorAction SilentlyContinue) { & $launcher install --root }
    if (-not (Test-Distro)) {
        Write-Host 'WSL was installed but the distro is not ready yet. Reboot Windows, then run this installer again.'
        exit 0
    }
}
wsl.exe --set-version $Distro 2 2>$null | Out-Null

# --- 2. User, systemd, packages (as root inside the distro) ------------------------------------
Write-Host '==> Preparing the Linux side (podman, git)'
$setup = @"
set -e
id $User >/dev/null 2>&1 || useradd -m -s /bin/bash $User
printf '[boot]\nsystemd=true\n[user]\ndefault=$User\n' > /etc/wsl.conf
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq podman git uidmap fuse-overlayfs slirp4netns curl ca-certificates
loginctl enable-linger $User 2>/dev/null || true
"@
$setup = $setup -replace "`r", ''
wsl.exe -d $Distro -u root -- bash -c $setup
if ($LASTEXITCODE -ne 0) { throw 'Linux-side setup failed.' }
wsl.exe --terminate $Distro   # restart so wsl.conf (systemd, default user) takes effect

# --- 3. Fetch tools, team code, simulator, build the image -------------------------------------
Write-Host '==> Running the Linux installer (first run downloads a few hundred MB)'
$inst = "curl -fsSL $RawBase/install.sh | FTC_TOOLS_REPO=$Repo bash"
wsl.exe -d $Distro -u $User -- bash -lc $inst
if ($LASTEXITCODE -ne 0) { throw 'install.sh failed inside WSL.' }

# --- 4. Windows launcher + shortcuts -----------------------------------------------------------
New-Item -ItemType Directory -Force $AppDir | Out-Null

$launch = @"
# Generated by install.ps1: starts the simulator inside WSL and reports errors in a dialog.
Add-Type -AssemblyName System.Windows.Forms
wsl.exe -d $Distro -u $User -- bash -lc '~/ftc-sim/tools/deck-launch.sh'
if (`$LASTEXITCODE -ne 0) {
    `$log = (wsl.exe -d $Distro -u $User -- bash -lc 'tail -n 15 ~/ftc-sim/last-run.log' 2>`$null) -join "``n"
    [System.Windows.Forms.MessageBox]::Show("The simulator stopped with an error.``n``n`$log", 'FTC Simulator') | Out-Null
}
"@
Set-Content -Path (Join-Path $AppDir 'launch.ps1') -Value $launch -Encoding UTF8

# Icon: wrap the PNG in a single-image .ico (PNG-in-ICO is supported on Vista+).
$png = Join-Path $AppDir 'ftc-sim.png'
Invoke-WebRequest "$RawBase/ftc-sim.png" -OutFile $png
$ico = Join-Path $AppDir 'ftc-sim.ico'
Add-Type -AssemblyName System.Drawing
$img = [System.Drawing.Image]::FromFile($png); $w = [Math]::Min($img.Width, 256); $h = [Math]::Min($img.Height, 256); $img.Dispose()
$bytes = [IO.File]::ReadAllBytes($png)
$ms = New-Object IO.MemoryStream; $bw = New-Object IO.BinaryWriter $ms
$bw.Write([UInt16]0); $bw.Write([UInt16]1); $bw.Write([UInt16]1)
$bw.Write([byte]($w % 256)); $bw.Write([byte]($h % 256)); $bw.Write([byte]0); $bw.Write([byte]0)
$bw.Write([UInt16]1); $bw.Write([UInt16]32); $bw.Write([UInt32]$bytes.Length); $bw.Write([UInt32]22)
$bw.Write($bytes); $bw.Flush()
[IO.File]::WriteAllBytes($ico, $ms.ToArray())

$shell = New-Object -ComObject WScript.Shell
$targets = @(
    (Join-Path ([Environment]::GetFolderPath('Desktop')) 'FTC Simulator.lnk'),
    (Join-Path ([Environment]::GetFolderPath('Programs')) 'FTC Simulator.lnk')
)
foreach ($t in $targets) {
    $s = $shell.CreateShortcut($t)
    $s.TargetPath = (Get-Command powershell.exe).Source
    $s.Arguments = "-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$(Join-Path $AppDir 'launch.ps1')`""
    $s.IconLocation = $ico
    $s.Description = 'Pull the latest team code and launch the virtual_robot simulator'
    $s.Save()
}
Write-Host "Done. Launch 'FTC Simulator' from the Desktop or Start menu. Log: ~/ftc-sim/last-run.log inside $Distro."
